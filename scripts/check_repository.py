"""Check Python APIs and render/validate Kubernetes resources without a cluster.

Run in docker/ops.Dockerfile. --write-api updates the generated API index;
normal execution fails if that index is stale. No Kubernetes apply is performed.
"""
import argparse
import ast
import json
from pathlib import Path
import subprocess
import tempfile

import yaml

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ["base", "overlays/dev", "overlays/external", "jobs/bootstrap", "jobs/transfer", "jobs/pipeline", "jobs/train", "jobs/volume-access"]


def python_inventory():
    """Compile every package module and document its exported functions/classes."""
    lines = ["# Python API index", "", "Generated by `scripts/check_repository.py --write-api` inside the ops container.",
             "Public entrypoints are listed by module. See each docstring for its contract.", ""]
    functions = 0
    for path in sorted((ROOT/"src/chess_lakehouse").rglob("*.py")):
        tree = ast.parse(path.read_text(), filename=str(path))
        compile(tree, str(path), "exec")
        relative = path.relative_to(ROOT)
        nodes = [node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and not node.name.startswith("_")]
        if not nodes: continue
        lines.extend([f"## `{relative}`", ""])
        for node in nodes:
            doc = ast.get_docstring(node)
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not doc: raise ValueError(f"Missing public function docstring: {relative}:{node.name}")
                functions += 1
            summary = doc.splitlines()[0] if doc else "Data structure; fields and methods are defined in the source."
            lines.append(f"- `{node.name}`: {summary}")
        lines.append("")
    return "\n".join(lines), functions


def manifests():
    """Strictly validate each overlay and check workload mount/reference contracts."""
    reports = {}
    base = None
    for target in TARGETS:
        result = subprocess.run(["kubectl", "kustomize", str(ROOT/"deploy/k8s"/target)], capture_output=True, text=True, check=True)
        documents = list(yaml.safe_load_all(result.stdout))
        with tempfile.NamedTemporaryFile(mode="w", suffix=".yaml") as stream:
            stream.write(result.stdout); stream.flush()
            validation = subprocess.run(["kubeconform", "-strict", "-summary", "-kubernetes-version", "1.36.0", stream.name], capture_output=True, text=True)
        if validation.returncode: raise ValueError(target+": "+validation.stdout+validation.stderr)
        keys = [(d["kind"], d["metadata"].get("namespace"), d["metadata"]["name"]) for d in documents]
        if len(keys)!=len(set(keys)): raise ValueError("Duplicate resources: "+target)
        if target=="base": base=documents
        available = documents if target in ("base", "overlays/dev", "overlays/external") else documents+base
        configmaps = {d["metadata"]["name"]: d.get("data", {}) for d in available if d["kind"]=="ConfigMap"}
        claims = {d["metadata"]["name"] for d in available if d["kind"]=="PersistentVolumeClaim"}
        for document in documents:
            if document["kind"] not in ("Deployment", "StatefulSet", "Job"): continue
            spec = document["spec"]["template"]["spec"]
            assert spec.get("automountServiceAccountToken") is False
            assert spec["securityContext"]["runAsNonRoot"] is True
            volumes = {v["name"]: v for v in spec.get("volumes", [])}
            for volume in volumes.values():
                if "persistentVolumeClaim" in volume: assert volume["persistentVolumeClaim"]["claimName"] in claims
            for container in spec["containers"]:
                assert container["resources"].get("limits") and container["resources"].get("requests")
                assert container["securityContext"].get("allowPrivilegeEscalation") is False
                for mount in container.get("volumeMounts", []):
                    assert mount["name"] in volumes or document["kind"]=="StatefulSet"
                for env in container.get("env", []):
                    ref = env.get("valueFrom", {}).get("configMapKeyRef")
                    if ref: assert ref["key"] in configmaps[ref["name"]]
                for env in container.get("envFrom", []):
                    if "configMapRef" in env: assert env["configMapRef"]["name"] in configmaps
            if document["kind"]=="Deployment": assert document["spec"]["replicas"]==0
        reports[target] = {"resources": len(documents), "schema": "passed"}
    return reports


def main():
    """Emit a machine-readable validation summary and optionally update API docs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-api", action="store_true")
    parser.add_argument("--skip-kubernetes", action="store_true")
    args = parser.parse_args()
    index, functions = python_inventory()
    path = ROOT/"docs/python-api.md"
    if args.write_api: path.write_text(index)
    elif not path.exists() or path.read_text()!=index: raise ValueError("API index is stale; run with --write-api")
    print(json.dumps({"public_functions_documented": functions, "kubernetes": {} if args.skip_kubernetes else manifests()}, indent=2))


if __name__=="__main__": main()
